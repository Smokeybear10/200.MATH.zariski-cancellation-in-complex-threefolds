"""Finite exact controls for genuine E-time profile (1,1,2,2).

Three actual polynomial frames have explicit two-sided inverses and slice u.
They exhibit quadratic-slot shifts (1,0), (3,2), and (3,3), respectively.
The first has a height-two initial kernel and deliberately defeats a
principal-factor multiplicity inference. The second has a weight-two
principal relation; the third has a weight-three principal relation whose
actual evaluation is affine but NOT invariant.

Separate synthetic monomial maps check weighted multiplicity, finite
graded dimensions, and the arithmetic of the invariant-growth comparison.
Their weight-five example is not an actual frame: the written157 theorem
excludes such a height-one relation under its full actual hypotheses.
Finite checks do not prove that theorem, its growth argument, recognition,
coordinate entry, or cancellation. The algebra generated by four leading
forms is not identified with the full associated graded ring.
No previous checker or solver is imported.
"""

import itertools
import math
import unittest

import sympy as sp


class TwoLinearTwoQuadraticControls(unittest.TestCase):
    WEIGHTS = (1, 1, 2, 2)

    def zero(self, expression):
        self.assertEqual(sp.expand(expression), 0)

    @staticmethod
    def deriv(expression, variables, coefficients):
        return sp.expand(sum(c*sp.diff(expression, v)
                             for v, c in zip(variables, coefficients)))

    @staticmethod
    def degree(expression, variable):
        return sp.Poly(sp.expand(expression), variable).degree()

    @classmethod
    def weight(cls, expression, variables):
        return max(sum(w*i for w, i in zip(cls.WEIGHTS, powers))
                   for powers, coefficient in sp.Poly(expression, *variables).terms())

    def actual_frame(self, base, original, forward, inverse, determinant=1):
        to_base, to_original = dict(zip(original, forward)), dict(zip(base, inverse))
        for variable, expression in zip(base, inverse):
            self.zero(expression.xreplace(to_base)-variable)
        for variable, expression in zip(original, forward):
            self.zero(expression.xreplace(to_original)-variable)
        u = base[0]
        self.assertEqual(tuple(self.degree(f, u) for f in forward), self.WEIGHTS)
        self.zero(sp.diff(u, u)-1)
        self.zero(sp.Matrix(forward).jacobian(base).det()-determinant)
        for f, d in zip(forward, self.WEIGHTS):
            self.zero(sp.diff(f, u, d+1))
            # Ordinary leading coefficients include the factorial division.
            self.zero(sp.Poly(f, u).LC()-sp.diff(f, u, d)/math.factorial(d))
        return to_base

    def partial_control(self, base, forward, coefficients, slot, expected_shift):
        u = base[0]
        T = lambda f: self.deriv(f, base, coefficients)
        for index, f in enumerate(forward):
            self.zero(T(f)-int(index == slot))
        self.zero(T(u))
        self.assertEqual(max(self.degree(c, u) for c in coefficients[1:]),
                         expected_shift)
        top = tuple(sp.expand(c).coeff(u, expected_shift) for c in coefficients[1:])
        self.assertTrue(any(c != 0 for c in top))
        for f in forward:
            self.zero(self.deriv(sp.Poly(f, u).LC(), base[1:], top))
        # These explicit partials happen to square to zero on base generators.
        # The universal statement is local nilpotence, not this stronger bound.
        for v in base:
            self.zero(T(T(v)))
        return T, top

    def test_actual_low_shifts_and_height_two_multiplicity_failure(self):
        u, a, b, c = base = sp.symbols("u a b c")
        X, Y, Z, W = original = sp.symbols("X Y Z W")
        forward = (u, a+b*u, b+u*u, c+u*u)
        inverse = (X, Y-X*(Z-X*X), Z-X*X, W-X*X)
        to_base = self.actual_frame(base, original, forward, inverse)
        TZ, topZ = self.partial_control(base, forward, (0, -u, 1, 0), 2, 1)
        TW, topW = self.partial_control(base, forward, (0, 0, 0, 1), 3, 0)
        self.assertEqual(topZ, (-1, 0, 0))
        self.assertEqual(topW, (0, 0, 1))

        eta = sp.symbols("eta")
        theta = dict(zip(original, (eta, b*eta, eta**2, eta**2)))
        F, G = Z-X*X, W-X*X
        self.zero(F.xreplace(theta))
        self.zero(G.xreplace(theta))
        # The quotient by (F,G) is C[X,Y], and its images are independent:
        # eta=X and b=Y/X recover its fraction field. Thus this actual
        # initial kernel has height TWO, not the principal ideal (F).
        self.assertEqual(sp.rem(G, F, Z), G)
        self.assertNotEqual(G, 0)
        P = F*G
        self.assertEqual(self.weight(P, original), 4)
        derivative = sp.diff(P, Z)
        self.zero(derivative-G)
        self.zero(derivative.xreplace(theta))
        actual = sp.expand(P.xreplace(to_base))
        self.zero(actual-b*c)
        self.zero(TZ(actual)-c)
        self.zero(derivative.xreplace(to_base)-TZ(actual))
        self.assertEqual(self.degree(TZ(actual), u), 0)
        self.assertNotEqual(self.degree(TZ(actual), u), 4-2)
        # F has exact multiplicity one in P, but G is another kernel element.
        # Dropping the full-kernel=(F) hypothesis would predict the wrong degree.

    def test_actual_shift_three_weight_two_and_exact_multiplicity(self):
        u, a, b, c = base = sp.symbols("u a b c")
        X, Y, Z, W = original = sp.symbols("X Y Z W")
        y0, z0 = a+b*u, b+c*u
        forward = (u, y0, z0+y0*y0, c+u*z0)
        projected = Z-Y*Y
        inv_c = W-X*projected
        inv_b = projected-X*inv_c
        inverse = (X, Y-X*inv_b, inv_b, inv_c)
        to_base = self.actual_frame(base, original, forward, inverse)
        TZ, topZ = self.partial_control(
            base, forward, (0, -u-u**3, 1+u*u, -u), 2, 3)
        TW, topW = self.partial_control(
            base, forward, (0, u*u, -u, 1), 3, 2)
        self.assertEqual(topZ, (-1, 0, 0))
        self.assertEqual(topW, (1, 0, 0))

        eta = sp.symbols("eta")
        theta = dict(zip(original, (eta, b*eta, b*b*eta**2, c*eta**2)))
        F, G = Z-Y*Y, Z+W
        self.zero(F.xreplace(theta))
        self.assertNotEqual(sp.expand(G.xreplace(theta)), 0)
        # C[X,Y,W] embeds with fraction-field recovery eta=X,b=Y/X,c=W/X².
        # Together with eliminating Z=Y², this proves the exact kernel (F).
        for ell in (1, 2, 3, 4):
            with self.subTest(multiplicity=ell):
                topP = F**ell*G
                P = topP+X+Y+W
                M = self.weight(P, original)
                self.assertEqual(M, 2*ell+2)
                self.assertEqual(sp.rem(G, F, Z), Y*Y+W)
                differentiated_top = sp.diff(topP, Z, ell)
                expected_residue = math.factorial(ell)*G
                self.zero(sp.rem(differentiated_top-expected_residue, F, Z))
                actual = sp.expand(P.xreplace(to_base))
                transported = actual
                for _ in range(ell):
                    transported = TZ(transported)
                direct = sp.diff(P, Z, ell).xreplace(to_base)
                self.zero(transported-direct)
                self.assertEqual(self.degree(actual, u), ell+2)
                self.assertEqual(self.degree(transported, u), M-2*ell)
                self.zero(sp.Poly(transported, u).LC()
                          -math.factorial(ell)*(b*b+c))
                self.assertGreaterEqual(self.degree(actual, u), M-(3+2)*ell)

        # The weight-two relation gives a genuine third affine slot.
        self.zero(F.xreplace(to_base)-z0)
        self.zero(sp.diff(F.xreplace(to_base), u, 2))
        self.zero((projected+Y*Y)-Z)

    def test_actual_weight_three_relation_is_not_an_invariant(self):
        u, a, b, c = base = sp.symbols("u a b c")
        X, Y, Z, W = original = sp.symbols("X Y Z W")
        y0, z0, w0 = a+b*u, c-b*u, b+u
        H0 = sp.expand(u*z0+y0*w0)
        p = a+c+b*b
        self.zero(H0-(a*b+u*p))
        forward = (u, y0, z0+y0*H0, w0-u*H0)
        H = X*Z+Y*W
        old_z, old_w = Z-Y*H, W+X*H
        inv_b = old_w-X
        inverse = (X, Y-X*inv_b, inv_b, old_z+X*inv_b)
        to_base = self.actual_frame(base, original, forward, inverse, determinant=-1)
        self.zero(H.xreplace(to_base)-H0)
        self.zero(X*old_z+Y*old_w-H)
        self.assertEqual(self.degree(H.xreplace(to_base), u), 1)
        self.zero(sp.diff(H.xreplace(to_base), u)-p)
        self.assertNotEqual(p, 0)

        TZ, topZ = self.partial_control(
            base, forward, (0, -u**3, u*u, 1-a*u-b*u*u+u**3), 2, 3)
        TW, topW = self.partial_control(
            base, forward,
            (0, -u-a*u*u-b*u**3, 1+a*u+b*u*u,
             -a*a+(1-2*a*b)*u+(a-b*b)*u*u+b*u**3), 3, 3)
        self.assertEqual(topZ, (-1, 0, 1))
        self.assertEqual(topW, (-b, 0, b))
        self.zero(TZ(H0)-u)
        self.zero(TW(H0)-y0)
        eta = sp.symbols("eta")
        theta = dict(zip(original, (eta, b*eta, b*p*eta**2, -p*eta**2)))
        self.zero(H.xreplace(theta))
        self.assertEqual(self.weight(H, original), 3)
        # The images recover eta, b, p rationally, so their transcendence
        # degree is three. XZ+YW is irreducible by primitive linear Gauss,
        # hence it generates the height-one kernel. No assertion H is invariant.
        self.zero(sp.Matrix((b, p)).jacobian((a, b, c))[:, :2].det()+1)

    def test_formal_weighted_multiplicity_dimensions_and_growth_hypotheses(self):
        X, Y, Z, W = variables = sp.symbols("X Y Z W")
        eta, b, c = sp.symbols("eta b c")
        cases = (
            (3, X*W-Y*Z, (eta, b*eta, c*eta**2, b*c*eta**2), 1),
            (4, X*X*W-Z*Z, (eta, b*eta, c*eta**2, c*c*eta**2), 2),
            (5, X**3*W-Y*Z*Z, (eta, b*eta, c*eta**2, b*c*c*eta**2), 3),
        )
        # These are SYNTHETIC leading maps, not coordinate maps. Each binomial
        # is primitive linear in W and irreducible by Gauss; eta,b,c are
        # recovered rationally from X,Y,Z. Thus its full prime kernel is (F).
        # In particular weight five is algebraically possible before imposing
        # the actual LND shift and invariant-growth hypotheses of the theorem.
        max_weight = 8
        monomials = []
        for exponents in itertools.product(range(max_weight+1), repeat=2):
            for quadratics in itertools.product(range(max_weight//2+1), repeat=2):
                powers = exponents+quadratics
                weight = sum(w*i for w, i in zip(self.WEIGHTS, powers))
                if weight <= max_weight:
                    monomials.append((powers, weight))
        source_counts = [sum(weight == m for _, weight in monomials)
                         for m in range(max_weight+1)]
        for d, F, images, x_power in cases:
            with self.subTest(formal_relation_weight=d):
                theta = dict(zip(variables, images))
                self.zero(F.xreplace(theta))
                self.assertEqual(self.weight(F, variables), d)
                for ell in (1, 2, 3):
                    G = Z+W
                    P = F**ell*G
                    derivative = sp.diff(P, W, ell)
                    residue = math.factorial(ell)*G*sp.diff(F, W)**ell
                    self.zero((derivative-residue).xreplace(theta))
                    evaluated = sp.expand(derivative.xreplace(theta))
                    self.assertNotEqual(evaluated, 0)
                    self.assertEqual(self.degree(evaluated, eta), d*ell+2-2*ell)

                # Exact finite graded ranks by independent monomial signatures.
                # Standard monomials avoid X^x_power*W, the leading term of F.
                signatures = [set() for _ in range(max_weight+1)]
                standard = [set() for _ in range(max_weight+1)]
                for powers, weight in monomials:
                    ix, iy, iz, iw = powers
                    if d == 3:
                        signature = (weight, iy+iw, iz+iw)
                    elif d == 4:
                        signature = (weight, iy, iz+2*iw)
                    else:
                        signature = (weight, iy+iw, iz+2*iw)
                    signatures[weight].add(signature)
                    if ix < x_power or iw == 0:
                        self.assertNotIn(signature, standard[weight])
                        standard[weight].add(signature)
                for weight in range(max_weight+1):
                    expected = source_counts[weight]
                    if weight >= d:
                        expected -= source_counts[weight-d]
                    self.assertEqual(len(signatures[weight]), expected)
                    self.assertEqual(standard[weight], signatures[weight])

        # The written argument, not these finite numbers, supplies three
        # independent ACTUAL invariants and the upper filtered-dimension bound.
        # At the hypothetical equality d=k+2 all invariant tops would be scalar
        # powers of F. Sample D values compare that linear count with three
        # independent-variable monomials. They are arithmetic sanity checks.
        for k in range(4):
            d = k+2
            for D in (d, 3*d+1):
                j = D+1
                lower = sum(1 for i in range(j+1) for r in range(j-i+1)
                            for t in range(j-i-r+1))
                upper = len(range(0, D*j+1, d))
                self.assertEqual(lower, math.comb(j+3, 3))
                self.assertEqual(upper, D*j//d+1)
                self.assertGreater(lower, upper)


if __name__ == "__main__":
    unittest.main()
